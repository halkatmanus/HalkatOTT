package com.halkatott.tv;

import android.content.ActivityNotFoundException;
import android.content.ComponentName;
import android.content.Context;
import android.content.Intent;
import android.net.Uri;
import android.os.FileObserver;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;
import android.widget.Toast;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Bridges the native HalkatOTT binary to Android's intent system.
 *
 * The binary thinks it runs under Termux and launches players with
 * "termux-am start -a android.intent.action.VIEW -d URL -t video/* -e key value ...".
 * We hand it a tiny shell script named "termux-am" (see {@link #install}) which drops its arguments
 * into a request file; this class watches for those files and starts the matching Intent itself,
 * so nothing depends on the "am" shell command being usable from an app uid.
 */
final class PlayerBridge {
    private static final String TAG = "HalkatOTT/Bridge";

    private final Context context;
    private final File requestDir;
    private final Handler ui = new Handler(Looper.getMainLooper());
    private FileObserver observer;

    PlayerBridge(Context context, File requestDir) {
        this.context = context.getApplicationContext();
        this.requestDir = requestDir;
    }

    /** Writes the "termux-am" shim into binDir and returns it. */
    File install(File binDir) throws IOException {
        if (!binDir.isDirectory() && !binDir.mkdirs()) throw new IOException("cannot create " + binDir);
        if (!requestDir.isDirectory() && !requestDir.mkdirs()) throw new IOException("cannot create " + requestDir);
        String script = "#!/system/bin/sh\n"
                + "# Generated by HalkatOTT: forwards an \"am start\"-style request to the app.\n"
                + "d='" + requestDir.getAbsolutePath() + "'\n"
                + "t=\"$d/.tmp.$$\"\n"
                + ": > \"$t\" || exit 1\n"
                + "for a in \"$@\"; do\n"
                + "  printf '%s\\n' \"$a\" >> \"$t\"\n"
                + "done\n"
                + "mv \"$t\" \"$d/req.$$\"\n"
                + "exit 0\n";
        File shim = new File(binDir, "termux-am");
        try (FileOutputStream out = new FileOutputStream(shim)) {
            out.write(script.getBytes(StandardCharsets.UTF_8));
        }
        shim.setReadable(true, false);
        shim.setExecutable(true, false);
        return shim;
    }

    void start() {
        File[] stale = requestDir.listFiles();
        if (stale != null) for (File f : stale) f.delete();
        observer = new FileObserver(requestDir.getAbsolutePath(), FileObserver.MOVED_TO) {
            @Override
            public void onEvent(int event, String path) {
                if (path != null && path.startsWith("req.")) handleRequest(new File(requestDir, path));
            }
        };
        observer.startWatching();
    }

    void stop() {
        if (observer != null) observer.stopWatching();
        observer = null;
    }

    private void handleRequest(File file) {
        final List<String> args = new ArrayList<>();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(new FileInputStream(file), StandardCharsets.UTF_8))) {
            String line;
            while ((line = r.readLine()) != null) args.add(line);
        } catch (IOException e) {
            Log.w(TAG, "cannot read request " + file, e);
            return;
        } finally {
            //noinspection ResultOfMethodCallIgnored
            file.delete();
        }
        ui.post(new Runnable() {
            @Override
            public void run() {
                launch(args);
            }
        });
    }

    /** Translates the subset of "am start" arguments that HalkatOTT uses into an Intent. */
    private void launch(List<String> args) {
        Intent intent = new Intent(Intent.ACTION_VIEW);
        String data = null;
        String type = null;
        int n = args.size();
        for (int i = 0; i < n; i++) {
            String a = args.get(i);
            switch (a) {
                case "-a":
                    if (i + 1 < n) intent.setAction(args.get(++i));
                    break;
                case "-d":
                    if (i + 1 < n) data = args.get(++i);
                    break;
                case "-t":
                    if (i + 1 < n) type = args.get(++i);
                    break;
                case "-n":
                    if (i + 1 < n) {
                        ComponentName cn = ComponentName.unflattenFromString(args.get(++i));
                        if (cn != null) intent.setComponent(cn);
                    }
                    break;
                case "-e":
                case "--es":
                    if (i + 2 < n) {
                        intent.putExtra(args.get(i + 1), args.get(i + 2));
                        i += 2;
                    }
                    break;
                case "--eu":
                    if (i + 2 < n) {
                        intent.putExtra(args.get(i + 1), Uri.parse(args.get(i + 2)));
                        i += 2;
                    }
                    break;
                case "--esal":
                    if (i + 2 < n) {
                        intent.putStringArrayListExtra(args.get(i + 1),
                                new ArrayList<>(Arrays.asList(args.get(i + 2).split(","))));
                        i += 2;
                    }
                    break;
                case "--ez":
                    if (i + 2 < n) {
                        intent.putExtra(args.get(i + 1), Boolean.parseBoolean(args.get(i + 2)));
                        i += 2;
                    }
                    break;
                case "--user":
                    i++; // always the current user
                    break;
                default:
                    break; // "start" and anything unknown
            }
        }
        if (data != null) {
            Uri uri = data.startsWith("/") ? Uri.fromFile(new File(data)) : Uri.parse(data);
            if (type != null) intent.setDataAndType(uri, type);
            else intent.setData(uri);
        } else if (type != null) {
            intent.setType(type);
        }
        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
        try {
            context.startActivity(intent);
        } catch (ActivityNotFoundException e) {
            Log.w(TAG, "no activity for " + intent, e);
            Toast.makeText(context, "No video player installed. Install VLC, MX Player or similar.", Toast.LENGTH_LONG).show();
        } catch (RuntimeException e) {
            Log.w(TAG, "cannot start player", e);
            Toast.makeText(context, "Cannot start video player: " + e.getMessage(), Toast.LENGTH_LONG).show();
        }
    }
}
